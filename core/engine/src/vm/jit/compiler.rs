    /// Get a helper function reference for use in the current function being built.
    fn helper_ref(
        &mut self,
        builder: &mut FunctionBuilder<'_>,
        name: &str,
    ) -> cranelift_codegen::ir::FuncRef {
        let id = self.helpers.funcs[name];
        self.module.declare_func_in_func(id, builder.func)
    }

    /// Compile a [`CodeBlock`] into a native function.
    pub(crate) fn compile(&mut self, code: &CodeBlock) -> Option<JitFn> {
        if !super::can_compile(code) {
            return None;
        }

        let name = format!("jit_fn_{}", self.func_counter);
        self.func_counter += 1;

        let mut sig = self.module.make_signature();
        sig.params.push(AbiParam::new(self.ptr_type)); // &mut Context
        sig.params.push(AbiParam::new(self.ptr_type)); // *mut u64 (register base)
        sig.returns.push(AbiParam::new(types::I64));

        let func_id = self
            .module
            .declare_function(&name, Linkage::Local, &sig)
            .expect("declare function");

        let mut func =
            Function::with_name_signature(UserFuncName::testcase(&name), sig.clone());

        let mut func_ctx = FunctionBuilderContext::new();
        {
            let mut builder = FunctionBuilder::new(&mut func, &mut func_ctx);

            let entry_block = builder.create_block();
            builder.append_block_params_for_function_params(entry_block);
            builder.switch_to_block(entry_block);

            let ctx_ptr = builder.block_params(entry_block)[0];
            let reg_base_arg = builder.block_params(entry_block)[1];

            // Stack slot for jit_call to update reg_base after callee returns.
            let reg_base_slot = builder.create_sized_stack_slot(
                cranelift_codegen::ir::StackSlotData::new(
                    cranelift_codegen::ir::StackSlotKind::ExplicitSlot,
                    8, 0,
                ),
            );
            builder.ins().stack_store(reg_base_arg, reg_base_slot, 0);

            // Cranelift Variable for reg_base — handles SSA phi nodes
            // automatically at block joins (loop headers, merge blocks).
            let reg_base_var = builder.declare_var(self.ptr_type);
            builder.def_var(reg_base_var, reg_base_arg);

            self.translate_body(
                &mut builder, ctx_ptr, reg_base_var, reg_base_slot, code, entry_block,
            );

            builder.finalize();
        }

        let mut ctx = cranelift_codegen::Context::for_function(func);
        if let Err(e) = self.module.define_function(func_id, &mut ctx) {
            // Cranelift verification or compilation failed — fall back to interpreter.
            self.module.clear_context(&mut ctx);
            return None;
        }
        self.module.clear_context(&mut ctx);
        self.module.finalize_definitions().expect("finalize");

        let code_ptr = self.module.get_finalized_function(func_id);

        // SAFETY: The generated code has signature (ptr) -> i64, matching RawJitFn.
        let raw: RawJitFn = unsafe { std::mem::transmute(code_ptr) };
        Some(JitFn(raw))
    }

    /// Emit a call to a fallible helper (returns i64: 0=ok, nonzero=error).
    /// On error, jumps to error_block. On success, continues in a new block
    /// and updates reg_base_var from the stack slot (the helper may have
    /// triggered a Call that resized the VM stack).
    fn emit_fallible_call(
        builder: &mut FunctionBuilder<'_>,
        func_ref: cranelift_codegen::ir::FuncRef,
        args: &[Value],
        error_block: Block,
        reg_base_var: cranelift_frontend::Variable,
        reg_base_slot: cranelift_codegen::ir::StackSlot,
        ptr_type: Type,
    ) {
        let result = builder.ins().call(func_ref, args);
        let tag = builder.inst_results(result)[0];
        let zero = builder.ins().iconst(types::I64, 0);
        let ok = builder.ins().icmp(cranelift_codegen::ir::condcodes::IntCC::Equal, tag, zero);

        let continue_block = builder.create_block();
        builder.ins().brif(ok, continue_block, &[], error_block, &[]);

        builder.switch_to_block(continue_block);
        // Reload reg_base — the helper may have caused stack reallocation.
        let new_base = builder.ins().stack_load(ptr_type, reg_base_slot, 0);
        builder.def_var(reg_base_var, new_base);
    }

    /// Load a JsValue (u64) from the register file at the given index.
    fn load_reg(
        builder: &mut FunctionBuilder<'_>,
        reg_base: Value,
        index: u32,
    ) -> Value {
        let offset = (index as i32) * 8;
        builder
            .ins()
            .load(types::I64, cranelift_codegen::ir::MemFlags::trusted(), reg_base, offset)
    }

    /// Store a JsValue (u64) to the register file at the given index.
    fn store_reg(
        builder: &mut FunctionBuilder<'_>,
        reg_base: Value,
        index: u32,
        value: Value,
    ) {
        let offset = (index as i32) * 8;
        builder
            .ins()
            .store(cranelift_codegen::ir::MemFlags::trusted(), value, reg_base, offset);
    }

    // NaN-boxing constants.
    const MASK_KIND: u64 = 0x7FFF_0000_0000_0000;
    const MASK_NAN: u64 = 0x7FF0_0000_0000_0000;
    const MASK_INT32: u64 = 0x7FF9_0000_0000_0000;
    const MASK_BOOLEAN: u64 = 0x7FFA_0000_0000_0000;
    const MASK_OTHER: u64 = 0x7FFB_0000_0000_0000;
    /// Pointer types (Object, String, Symbol, BigInt) have tags >= this value.
    const MASK_OBJECT: u64 = 0x7FFC_0000_0000_0000;
    // Specific constants.
    const VALUE_NULL: u64 = 0x7FFB_0000_0000_0000;
    const VALUE_UNDEFINED: u64 = 0x7FFB_0000_0000_0001;
    const VALUE_FALSE: u64 = 0x7FFA_0000_0000_0000;
    const VALUE_TRUE: u64 = 0x7FFA_0000_0000_0001;
    const VALUE_NAN: u64 = 0x7FF8_0000_0000_0000;
    const VALUE_POS_INF: u64 = 0x7FF0_0000_0000_0000;
    const VALUE_NEG_INF: u64 = 0xFFF0_0000_0000_0000;

    /// Integer binary operations that can be inlined with overflow check.
    fn emit_inlined_int_binop(
        &self,
        builder: &mut FunctionBuilder<'_>,
        ctx_ptr: Value,
        reg_base: Value,
        reg_base_var: cranelift_frontend::Variable,
        reg_base_slot: cranelift_codegen::ir::StackSlot,
        dst: u32,
        lhs: u32,
        rhs: u32,
        op: IntBinOp,
        slow_ref: cranelift_codegen::ir::FuncRef,
        error_block: Block,
    ) {
        let lhs_val = Self::load_reg(builder, reg_base, lhs);
        let rhs_val = Self::load_reg(builder, reg_base, rhs);

        let mask = builder.ins().iconst(types::I64, Self::MASK_KIND as i64);
        let int_tag = builder.ins().iconst(types::I64, Self::MASK_INT32 as i64);
        let lhs_tag = builder.ins().band(lhs_val, mask);
        let rhs_tag = builder.ins().band(rhs_val, mask);
        let lhs_is_int = builder.ins().icmp(cranelift_codegen::ir::condcodes::IntCC::Equal, lhs_tag, int_tag);
        let rhs_is_int = builder.ins().icmp(cranelift_codegen::ir::condcodes::IntCC::Equal, rhs_tag, int_tag);
        let both_int = builder.ins().band(lhs_is_int, rhs_is_int);

        let fast_block = builder.create_block();
        let slow_block = builder.create_block();
        let merge_block = builder.create_block();
        builder.ins().brif(both_int, fast_block, &[], slow_block, &[]);

        builder.switch_to_block(fast_block);
        let lhs_i32 = builder.ins().ireduce(types::I32, lhs_val);
        let rhs_i32 = builder.ins().ireduce(types::I32, rhs_val);
        let (result, overflow) = match op {
            IntBinOp::Sub => builder.ins().ssub_overflow(lhs_i32, rhs_i32),
            IntBinOp::Mul => builder.ins().smul_overflow(lhs_i32, rhs_i32),
        };

        let no_overflow = builder.create_block();
        builder.ins().brif(overflow, slow_block, &[], no_overflow, &[]);

        builder.switch_to_block(no_overflow);
        let result_u64 = builder.ins().uextend(types::I64, result);
        let mask32 = builder.ins().iconst(types::I64, 0xFFFF_FFFF_i64);
        let result_masked = builder.ins().band(result_u64, mask32);
        let result_tagged = builder.ins().bor(result_masked, int_tag);
        Self::store_reg(builder, reg_base, dst, result_tagged);
        builder.ins().jump(merge_block, &[]);

        builder.switch_to_block(slow_block);
        let d = builder.ins().iconst(types::I32, i64::from(dst));
        let l = builder.ins().iconst(types::I32, i64::from(lhs));
        let r = builder.ins().iconst(types::I32, i64::from(rhs));
        Self::emit_fallible_call(builder, slow_ref, &[ctx_ptr, d, l, r], error_block, reg_base_var, reg_base_slot, self.ptr_type);
        builder.ins().jump(merge_block, &[]);

        builder.switch_to_block(merge_block);
    }

