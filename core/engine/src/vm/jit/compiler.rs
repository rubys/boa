/// Raw JIT function pointer.
/// Args: (`context_ptr`, `register_base_ptr`). Returns a tag: 0=Continue, 1=Break(Return), 2=Break(Throw).
/// The actual values (return value, exception) are communicated via Context.
type RawJitFn = unsafe extern "C" fn(*mut Context, *mut u64) -> u64;

/// A compiled JIT function that can be called in place of interpreting bytecode.
///
/// Wraps the raw function pointer with a safe calling convention.
#[derive(Clone, Copy)]
pub(crate) struct JitFn(RawJitFn);

impl std::fmt::Debug for JitFn {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_tuple("JitFn")
            .field(&(self.0 as *const ()))
            .finish()
    }
}

impl JitFn {
    /// Calls the raw JIT function, returning the tag directly
    /// (used by `jit_call` helper for direct JIT-to-JIT calls).
    pub(super) unsafe fn call_raw(self, context: *mut Context, reg_base: *mut u64) -> u64 {
        unsafe { (self.0)(context, reg_base) }
    }
    /// Call the JIT-compiled function.
    ///
    /// The JIT function returns a tag:
    ///
    /// - 0: `handle_return` returned `Continue` — frame was popped, result
    ///   pushed on the stack. This is the normal case.
    /// - 1: `handle_return` returned `Break(Return(value))` — `exit_early`
    ///   was set, value is in the `CompletionRecord`.
    /// - 2: An exception occurred — stored in `pending_exception`.
    pub(crate) fn call(self, context: &mut Context) -> CompletionRecord {
        // Pre-allocate stack capacity to prevent Vec reallocation during JIT
        // execution. If the stack Vec grows while the JIT is running, the
        // reg_base pointer becomes dangling. We reserve enough space for
        // nested calls (each frame needs up to ~64 registers + prologue + args).
        //
        // Use saturating arithmetic and clamp to a hard maximum to avoid
        // potential overflow or unbounded allocations when recursion_limit
        // is configured very large.
        const MAX_JIT_STACK_RESERVE: usize = 1 << 20; // ~8 MB cap
        let current_len = context.vm.stack.stack.len();
        let extra = context
            .vm
            .runtime_limits
            .recursion_limit()
            .saturating_mul(72);
        let uncapped = current_len.saturating_add(extra);
        let needed = uncapped.min(MAX_JIT_STACK_RESERVE.max(current_len));
        if uncapped > MAX_JIT_STACK_RESERVE.max(current_len) {
            // Required reservation exceeds cap — fall back to interpreter
            // to avoid potential reg_base invalidation during deep recursion.
            return context.run();
        }
        if context.vm.stack.stack.capacity() < needed {
            let additional = needed.saturating_sub(current_len);
            if additional > 0 {
                context.vm.stack.stack.reserve(additional);
            }
        }

        // Compute the register base pointer: &mut stack[rp] as *mut u64.
        let rp = context.vm.frame().rp as usize;
        let reg_base = context.vm.stack.stack[rp..].as_mut_ptr().cast::<u64>();

        // SAFETY: The raw function was generated by Cranelift with the correct
        // signature (two pointer args, returns u64). reg_base points into the
        // stack's heap allocation which remains valid because:
        // 1. We pre-reserved enough capacity above for the full recursion depth
        //    (each frame needs up to ~72 slots: prologue + args + registers).
        // 2. PushFromRegister/PopIntoRegister only add/remove a few values per
        //    frame, well within the reserved capacity.
        // 3. Call/New helpers explicitly update reg_base_slot after callee returns.
        // The reservation ensures the Vec never reallocates during JIT execution.
        let tag = unsafe { (self.0)(std::ptr::from_mut::<Context>(context), reg_base) };
        match tag {
            0 => {
                // Normal return — handle_return already popped the frame and
                // pushed the result on the stack. Return Normal completion.
                CompletionRecord::Normal(JsValue::undefined())
            }
            1 => {
                // exit_early was set — handle_return returned Break(Return(value)).
                CompletionRecord::Return(context.vm.take_return_value())
            }
            _ => {
                // Exception.
                CompletionRecord::Throw(context.vm.pending_exception.take().unwrap_or_else(|| {
                    crate::JsNativeError::error()
                        .with_message("JIT: unknown error")
                        .into()
                }))
            }
        }
    }
}

